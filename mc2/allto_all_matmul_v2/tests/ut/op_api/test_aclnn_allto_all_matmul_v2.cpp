TEST_P(AclnnAlltoAllMatmulV2Test, param)
{
    auto param = GetParam();
    op::SetPlatformSocVersion(param.soc);
    aclTensor *context = param.context.GetViewDims().empty() ? nullptr : param.context.ToAclTypeRawPtr();
    aclTensor *x1 = param.x1.GetViewDims().empty() ? nullptr : param.x1.ToAclTypeRawPtr();
    aclTensor *x2 = param.x2.GetViewDims().empty() ? nullptr : param.x2.ToAclTypeRawPtr();
    aclTensor *bias = param.bias.GetViewDims().empty() ? nullptr : param.bias.ToAclTypeRawPtr();
    aclTensor *x1Scale = param.x1Scale.GetViewDims().empty() ? nullptr : param.x1Scale.ToAclTypeRawPtr();
    aclTensor *x2Scale = param.x2Scale.GetViewDims().empty() ? nullptr : param.x2Scale.ToAclTypeRawPtr();
    aclTensor *output = param.output.GetViewDims().empty() ? nullptr : param.output.ToAclTypeRawPtr();
    aclTensor *alltoAllOut = param.alltoAllOut.GetViewDims().empty() ? nullptr : param.alltoAllOut.ToAclTypeRawPtr();

    auto ut = OP_API_UT(
        AlltoAllMatmulV2,
        INPUT(context, x1, x2, bias, x1Scale, x2Scale, param.group.c_str(), param.worldSize, param.hcclBufferSize,
              param.x1QuantMode, param.x2QuantMode, param.groupSize, param.commMode.c_str(), param.precisionMode),
        OUTPUT(output, alltoAllOut));
    uint64_t workspace_size = 0;
    aclOpExecutor *executor = nullptr;
    auto aclnnRet = ut.TestGetWorkspaceSizeWithNNopbaseInner(&workspace_size, executor);
    if (param.expectResult == ACLNN_SUCCESS) {
        EXPECT_NE(ACLNN_ERR_PARAM_INVALID, aclnnRet);
        // Call execute to cover the AlltoAllMatmulV2 execute function (L163-177).
        // Only when GetWorkspaceSize succeeds do we have a valid executor.
        if (aclnnRet == ACLNN_SUCCESS && executor != nullptr) {
            auto execRet = AlltoAllMatmulV2(nullptr, workspace_size, executor, nullptr);
            // Stubs make execute succeed; error path L173-174 stays uncovered.
            EXPECT_EQ(ACLNN_SUCCESS, execRet);
        }
    } else {
        EXPECT_EQ(param.expectResult, aclnnRet);
    }
}

