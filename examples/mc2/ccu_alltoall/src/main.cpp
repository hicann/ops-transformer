/*!
 * \file main.cpp
 * \brief CCU 直调 AllToAll + Blaze MXFP8 MatMul 双流通算融合——示例入口（单翻译单元，-xasc）
 *
 * 用法：./ccu_alltoall [--data <dir>] [precision|perf] [M] [tileM] [K] [N] [loop]
 * 默认：M=512, tileM=128, K=256, N=256, loop=10；数据目录 data/（scripts/gen_data.py
 * 生成，文件清单见其文件头；perf 模式跳过期望文件读取）
 *
 * 主干流程：main（参数解析 + aclInit + 每 device 一线程）→ RunAllToAllMatmul（初始化 +
 * 数据加载 + tiling 构造）→ InvokeAllToAllMatmul（Custom + 双流 sync）→
 * ReleaseAllToAllMatmulContext（循环外一次）。precision 全 rank 校验 PASS → 退出码 0。
 */

#include <functional>
#include <cstdlib>
#include <fstream>
#include <string>
#include "platform/platform_ascendc.h"

// 单翻译单元：CCU kernel + AIC kernel + host 编排 + tiling 构造（见 .asc 文件头说明）
#include "all_to_all_matmul_ccu.asc"

enum class RunMode {
    PRECISION,
    PERF
};

// 单 rank 线程的输入/输出参数（main 构造，RunAllToAllMatmul 消费）
struct ThreadContext {
    HcclRootInfo* rootInfo = nullptr;
    uint32_t rankId = 0;
    uint32_t rankSize = 0;
    RunMode mode{RunMode::PRECISION};
    uint64_t M{512};
    uint64_t tileM{128};
    uint64_t K{256};
    uint64_t N{256};
    uint32_t loopCount{10};
    std::string dataDir{"data"};
    int ret{0};
};

static void PrintUsage(const char* prog)
{
    std::cout << "Usage:\n"
              << "  " << prog << " [--data <dir>]                          # precision, defaults\n"
              << "  " << prog << " [--data <dir>] precision [M] [tileM] [K] [N]\n"
              << "  " << prog << " [--data <dir>] perf [M] [tileM] [K] [N] [loop]\n"
              << "  --data <dir>   data directory generated by scripts/gen_data.py (default: data)\n"
              << "Defaults: M=512, tileM=128, K=256, N=256, loop=10" << std::endl;
}

// 先抽取 --data <dir>（任意位置，缺参报错），剩余按位置参数解析；
// K 须为 64 倍数、tileM>0。rankSize 整除检查依赖设备查询，留在 main
static bool ParseCommandLine(int argc, char* argv[], ThreadContext& ctx)
{
    std::vector<char*> positional;
    positional.reserve(static_cast<size_t>(argc));
    for (int i = 1; i < argc; i++) {
        if (std::string(argv[i]) == "--data") {
            if (i + 1 >= argc) {
                std::cout << "ERROR: --data requires a directory argument" << std::endl;
                PrintUsage(argv[0]);
                return false;
            }
            ctx.dataDir = argv[i + 1];
            i++;
            continue;
        }
        positional.push_back(argv[i]);
    }

    if (!positional.empty()) {
        const std::string modeStr = positional[0];
        if (modeStr == "perf") {
            ctx.mode = RunMode::PERF;
        } else if (modeStr == "precision") {
            ctx.mode = RunMode::PRECISION;
        } else {
            std::cout << "ERROR: unknown mode '" << modeStr << "'" << std::endl;
            PrintUsage(argv[0]);
            return false;
        }
        try {
            if (positional.size() >= 2)
                ctx.M = std::stoull(positional[1]);
            if (positional.size() >= 3)
                ctx.tileM = std::stoull(positional[2]);
            if (positional.size() >= 4)
                ctx.K = std::stoull(positional[3]);
            if (positional.size() >= 5)
                ctx.N = std::stoull(positional[4]);
            if (positional.size() >= 6 && ctx.mode == RunMode::PERF) {
                ctx.loopCount = static_cast<uint32_t>(std::stoul(positional[5]));
            }
        } catch (const std::exception& e) {
            std::cout << "ERROR: invalid numeric argument (" << e.what() << ")" << std::endl;
            PrintUsage(argv[0]);
            return false;
        }
    }

    if (ctx.K == 0 || ctx.K % 64 != 0) {
        std::cout << "ERROR: K=" << ctx.K << " must be positive and divisible by 64 (MXFP8)" << std::endl;
        return false;
    }
    if (ctx.tileM == 0) {
        std::cout << "ERROR: tileM=" << ctx.tileM << " must be positive" << std::endl;
        return false;
    }
    return true;
}

// 读 dir/meta.txt（首行 "M K N R"）：不匹配则报错并打印 gen_data.py 再生成命令
static bool LoadCaseMeta(const std::string& dir, uint64_t M, uint64_t K, uint64_t N, uint32_t rankSize)
{
    std::ifstream ifs(dir + "/meta.txt");
    uint64_t metaM = 0;
    uint64_t metaK = 0;
    uint64_t metaN = 0;
    uint64_t metaR = 0;
    if (!ifs.is_open() || !(ifs >> metaM >> metaK >> metaN >> metaR)) {
        std::cout << "ERROR: cannot read " << dir << "/meta.txt (generate data first)" << std::endl;
        return false;
    }
    if (metaM != M || metaK != K || metaN != N || metaR != rankSize) {
        std::cout << "ERROR: data mismatch: " << dir << " holds M=" << metaM << " K=" << metaK << " N=" << metaN
                  << " R=" << metaR << ", requested M=" << M << " K=" << K << " N=" << N << " R=" << rankSize
                  << std::endl;
        std::cout << "  regenerate with: python3 scripts/gen_data.py --M " << M << " --K " << K << " --N " << N
                  << " --ranks " << rankSize << " --out " << dir << std::endl;
        return false;
    }
    return true;
}

// 文件 → device：mallocHost → 精确读 size 字节 → memcpy H2D → free
static int LoadFileToDevice(const std::string& path, void* devPtr, uint64_t size)
{
    void* hostBuf = nullptr;
    ACLCHECK(aclrtMallocHost(&hostBuf, size));
    std::ifstream ifs(path, std::ios::binary);
    if (!ifs.is_open()) {
        std::cout << "ERROR: cannot open " << path << std::endl;
        (void)aclrtFreeHost(hostBuf);
        return -1;
    }
    ifs.read(static_cast<char*>(hostBuf), static_cast<std::streamsize>(size));
    if (static_cast<uint64_t>(ifs.gcount()) != size) {
        std::cout << "ERROR: short read " << path << " (" << ifs.gcount() << " / " << size << " bytes)" << std::endl;
        (void)aclrtFreeHost(hostBuf);
        return -1;
    }
    aclError aclRet = aclrtMemcpy(devPtr, size, hostBuf, size, ACL_MEMCPY_HOST_TO_DEVICE);
    if (aclRet != ACL_SUCCESS) {
        (void)aclrtFreeHost(hostBuf);
        return static_cast<int>(aclRet);
    }
    ACLCHECK(aclrtFreeHost(hostBuf));
    return 0;
}

// 文件 → host buffer（期望文件比对用）
static int LoadFileToHost(const std::string& path, std::vector<uint8_t>& hostBuf, uint64_t size)
{
    hostBuf.resize(static_cast<size_t>(size));
    std::ifstream ifs(path, std::ios::binary);
    if (!ifs.is_open()) {
        std::cout << "ERROR: cannot open " << path << std::endl;
        return -1;
    }
    ifs.read(reinterpret_cast<char*>(hostBuf.data()), static_cast<std::streamsize>(size));
    if (static_cast<uint64_t>(ifs.gcount()) != size) {
        std::cout << "ERROR: short read " << path << " (" << ifs.gcount() << " / " << size << " bytes)" << std::endl;
        return -1;
    }
    return 0;
}

// 调用一次完整通算融合；CCU 资源经 a2aCtx 跨迭代复用（首帧 Prepare 分配，循环外统一 Release）
static HcclResult InvokeAllToAllMatmul(HcclComm comm, aclrtStream streamAicore, aclrtStream streamCcu,
                                       AllToAllMatmulContext& a2aCtx, void* x1, void* x1Scale, void* x2, void* x2Scale,
                                       void* output, void* workspace, uint64_t sendCount, uint64_t scaleCount,
                                       uint64_t workspaceSize, ccuAllToAllMatmulTilingData& tilingData)
{
    HCCLCHECK(AllToAllMatmulCustom(x1, x1Scale, x2, x2Scale, output, workspace, sendCount, scaleCount, workspaceSize,
                                   HCCL_DATA_TYPE_INT8, comm, streamAicore, streamCcu, tilingData, a2aCtx));

    aclError aclRet = aclrtSynchronizeStream(streamAicore);
    if (aclRet != ACL_SUCCESS) {
        return HCCL_E_INTERNAL;
    }
    aclRet = aclrtSynchronizeStream(streamCcu);
    if (aclRet != ACL_SUCCESS) {
        return HCCL_E_INTERNAL;
    }

    return HCCL_SUCCESS;
}

// precision 校验：D2H 读回 → 与期望文件逐元素 BF16 位型比对 → 首错定位 →
// 落盘 output/<rank>/npu_out.bin（无论成败）；0 = PASS
static int VerifyOutputAgainstExpect(uint32_t myRank, uint64_t blockRows, uint64_t N, void* output, uint64_t outputSize,
                                     const std::vector<uint8_t>& expectHost)
{
    void* resultBuff = nullptr;
    ACLCHECK(aclrtMallocHost(&resultBuff, outputSize));
    aclError aclRet = aclrtMemcpy(resultBuff, outputSize, output, outputSize, ACL_MEMCPY_DEVICE_TO_HOST);
    if (aclRet != ACL_SUCCESS) {
        (void)aclrtFreeHost(resultBuff);
        return static_cast<int>(aclRet);
    }
    const uint16_t* outHost = static_cast<const uint16_t*>(resultBuff);
    const uint16_t* expect = reinterpret_cast<const uint16_t*>(expectHost.data());

    const uint64_t totalElems = blockRows * N;
    uint64_t errCount = 0;
    bool hasFirstErr = false;
    uint64_t firstErrRow = 0;
    uint64_t firstErrCol = 0;
    uint16_t firstErrExpect = 0;
    uint16_t firstErrActual = 0;
    for (uint64_t m = 0; m < blockRows; m++) {
        const uint16_t* row = outHost + m * N;
        const uint16_t* expectRow = expect + m * N;
        for (uint64_t n = 0; n < N; n++) {
            if (row[n] != expectRow[n]) {
                errCount++;
                if (!hasFirstErr) {
                    hasFirstErr = true;
                    firstErrRow = m;
                    firstErrCol = n;
                    firstErrExpect = expectRow[n];
                    firstErrActual = row[n];
                }
            }
        }
    }

    if (errCount == 0) {
        std::cout << "rankId: " << myRank << ", A2A+MatMul PASS: all " << totalElems
                  << " output elems verified (vs y_expect file)" << std::endl;
    } else {
        std::cout << "rankId: " << myRank << ", A2A+MatMul FAIL: " << errCount << " / " << totalElems
                  << " elems mismatch" << std::endl;
        std::cout << "  first error at Y row " << firstErrRow << ", col " << firstErrCol << ": expect 0x" << std::hex
                  << firstErrExpect << ", actual 0x" << firstErrActual << std::dec << std::endl;
    }

    std::string outputDir = "output/" + std::to_string(myRank);
    if (system(("mkdir -p " + outputDir).c_str()) != 0) {
        std::cout << "rankId: " << myRank << ", warn: mkdir " << outputDir << " failed" << std::endl;
    }
    std::string outFile = outputDir + "/npu_out.bin";
    std::ofstream ofs(outFile, std::ios::binary);
    ofs.write(static_cast<const char*>(resultBuff), outputSize);
    ofs.close();
    std::cout << "rankId: " << myRank << ", output written to " << outFile << " (" << outputSize << " bytes)"
              << std::endl;

    ACLCHECK(aclrtFreeHost(resultBuff));
    return (errCount == 0) ? 0 : 1;
}

// 单 rank 执行入口（每 rank 一线程）：初始化 → 分配 → 加载数据 → tiling →
// 循环 Invoke → precision 校验 → 释放
int RunAllToAllMatmul(ThreadContext& ctx)
{
    if (ctx.rankSize > CCU_MAX_RANK_SIZE) {
        std::cout << "rankSize " << ctx.rankSize << " exceeds CCU_MAX_RANK_SIZE " << CCU_MAX_RANK_SIZE << std::endl;
        ctx.ret = HCCL_E_PARA;
        return ctx.ret;
    }
    const uint32_t myRank = ctx.rankId;
    const uint32_t rankSize = ctx.rankSize;
    const uint64_t M = ctx.M;
    const uint64_t tileM = ctx.tileM;
    const uint64_t K = ctx.K;
    const uint64_t N = ctx.N;
    constexpr uint64_t MXFP_DIVISOR = 64;
    constexpr uint64_t MXFP_MULTI = 2;
    const uint64_t scaleKLen = K / MXFP_DIVISOR * MXFP_MULTI;

    const uint64_t blockRows = M / rankSize;
    const uint64_t dataCommTurn = blockRows / tileM;
    const uint64_t sendCount = M * K;
    const uint64_t scaleCount = M * scaleKLen;
    const uint64_t weightCount = static_cast<uint64_t>(rankSize) * K * N;
    const uint64_t weightScaleCount = static_cast<uint64_t>(rankSize) * scaleKLen * N;
    const uint64_t outputCount = blockRows * N;
    const uint64_t sendSize = sendCount * 1;
    const uint64_t sendScaleSize = scaleCount * 1;
    const uint64_t weightSize = weightCount * 1;
    const uint64_t weightScaleSize = weightScaleCount * 1;
    const uint64_t outputSize = outputCount * 2;

    ACLCHECK(aclrtSetDevice(static_cast<int32_t>(ctx.rankId)));
    HcclComm hcclComm;
    HCCLCHECK(HcclCommInitRootInfo(ctx.rankSize, ctx.rootInfo, ctx.rankId, &hcclComm));
    aclrtStream streamAicore;
    ACLCHECK(aclrtCreateStream(&streamAicore));
    aclrtStream streamCcu;
    ACLCHECK(aclrtCreateStream(&streamCcu));

    // lambda 内 return 仅退出执行体，下方通信组/流/设备释放仍必然执行
    ctx.ret = [&]() -> int {
        void* x1 = nullptr;
        void* x1Scale = nullptr;
        void* x2 = nullptr;
        void* x2Scale = nullptr;
        void* output = nullptr;
        void* workspace = nullptr;
        const uint64_t workspaceSize = sendSize + sendScaleSize;
        ACLCHECK(aclrtMalloc(&x1, sendSize, ACL_MEM_MALLOC_HUGE_ONLY));
        ACLCHECK(aclrtMalloc(&x1Scale, sendScaleSize, ACL_MEM_MALLOC_HUGE_ONLY));
        ACLCHECK(aclrtMalloc(&x2, weightSize, ACL_MEM_MALLOC_HUGE_ONLY));
        ACLCHECK(aclrtMalloc(&x2Scale, weightScaleSize, ACL_MEM_MALLOC_HUGE_ONLY));
        ACLCHECK(aclrtMalloc(&output, outputSize, ACL_MEM_MALLOC_HUGE_ONLY));
        ACLCHECK(aclrtMalloc(&workspace, workspaceSize, ACL_MEM_MALLOC_HUGE_ONLY));
        auto freeAll = [&]() {
            (void)aclrtFree(workspace);
            (void)aclrtFree(output);
            (void)aclrtFree(x2Scale);
            (void)aclrtFree(x2);
            (void)aclrtFree(x1Scale);
            (void)aclrtFree(x1);
        };

        // 数据文件加载：x1/x1_scale 按 rank，x2/x2_scale 共享；precision 另读期望输出
        int loadRet = 0;
        std::vector<uint8_t> expectHost;
        do {
            if (!LoadCaseMeta(ctx.dataDir, M, K, N, rankSize)) {
                loadRet = -1;
                break;
            }
            loadRet = LoadFileToDevice(ctx.dataDir + "/x1_rank" + std::to_string(myRank) + ".bin", x1, sendSize);
            if (loadRet != 0) {
                break;
            }
            loadRet = LoadFileToDevice(ctx.dataDir + "/x1_scale_rank" + std::to_string(myRank) + ".bin", x1Scale,
                                       sendScaleSize);
            if (loadRet != 0) {
                break;
            }
            loadRet = LoadFileToDevice(ctx.dataDir + "/x2.bin", x2, weightSize);
            if (loadRet != 0) {
                break;
            }
            loadRet = LoadFileToDevice(ctx.dataDir + "/x2_scale.bin", x2Scale, weightScaleSize);
            if (loadRet != 0) {
                break;
            }
            if (ctx.mode == RunMode::PRECISION) {
                loadRet = LoadFileToHost(ctx.dataDir + "/y_expect_rank" + std::to_string(myRank) + ".bin", expectHost,
                                         outputSize);
            }
        } while (false);
        if (loadRet != 0) {
            freeAll();
            return loadRet;
        }

        // 构造统一 tiling：comm 仅 tileM（其余由 Validate/Prepare 填充）；matmul 由 SWAT 按shape 现算
        ccuAllToAllMatmulTilingData tilingData{};
        FillAllToAllMatmulTilingData(blockRows, N, K, tileM, tilingData);

        std::cout << "rankId: " << myRank << ", mode: " << (ctx.mode == RunMode::PERF ? "perf" : "precision")
                  << ", A2A+MXFP8 MatMul: rankSize=" << rankSize << ", M=" << M << ", blockRows=" << blockRows
                  << ", K=" << K << ", N=" << N << ", tileM=" << tileM << ", dataCommTurn=" << dataCommTurn
                  << " (scale 随轮 0 搭载)"
                  << ", usedCoreNum=" << tilingData.matmul.usedCoreNum << ", tiling[baseM=" << tilingData.matmul.baseM
                  << ",baseN=" << tilingData.matmul.baseN << ",baseK=" << tilingData.matmul.baseK
                  << ",stepK=" << static_cast<uint32_t>(tilingData.matmul.stepK)
                  << ",nBuf=" << static_cast<uint32_t>(tilingData.matmul.nBufferNum)
                  << ",dbL0c=" << static_cast<uint32_t>(tilingData.matmul.dbL0c)
                  << ",scaleKL1=" << tilingData.matmul.scaleKL1 << "]"
                  << ", x1=" << (sendSize / 1024) << "KB"
                  << ", workspace=" << ((sendSize + sendScaleSize) / 1024) << "KB";
        if (ctx.mode == RunMode::PERF) {
            std::cout << ", loop=" << ctx.loopCount;
        }
        std::cout << std::endl;

        AllToAllMatmulContext a2aCtx;
        const uint32_t totalRuns = (ctx.mode == RunMode::PERF) ? ctx.loopCount : 1;
        // event 计时旁证：串行迭代间隔 = 端到端单次耗时（含 launch/同步间隙）
        aclrtEvent iterStartEvent = nullptr;
        aclrtEvent iterEndEvent = nullptr;
        float eventElapsedTotalMs = 0.0F;
        // 重型算子：迭代间插入 4×128MB memset（~430us），设备忙期间各 rank host 完成
        // 下一帧提交，消除 rank 间起跑偏斜
        void* heavyBuf = nullptr;
        constexpr uint64_t HEAVY_BUF_SIZE = 128UL * 1024 * 1024; // 128MB
        constexpr uint32_t HEAVY_MEMSET_COUNT = 4;               // ~4×107us ≈ 430us
        if (ctx.mode == RunMode::PERF) {
            ACLCHECK(aclrtCreateEvent(&iterStartEvent));
            ACLCHECK(aclrtCreateEvent(&iterEndEvent));
            ACLCHECK(aclrtMalloc(&heavyBuf, HEAVY_BUF_SIZE, ACL_MEM_MALLOC_HUGE_ONLY));
        }
        int runRet = 0;
        for (uint32_t iter = 0; iter < totalRuns; iter++) {
            if (ctx.mode == RunMode::PERF) {
                ACLCHECK(aclrtRecordEvent(iterStartEvent, streamAicore));
            }
            runRet = static_cast<int>(InvokeAllToAllMatmul(hcclComm, streamAicore, streamCcu, a2aCtx, x1, x1Scale, x2,
                                                           x2Scale, output, workspace, sendCount, scaleCount,
                                                           sendSize + sendScaleSize, tilingData));
            if (runRet != HCCL_SUCCESS) {
                break;
            }
            if (ctx.mode == RunMode::PERF) {
                // Invoke 内部已 sync streamAicore，end event 立即完成；elapsed 为端到端单次耗时
                float iterMs = 0.0F;
                ACLCHECK(aclrtRecordEvent(iterEndEvent, streamAicore));
                ACLCHECK(aclrtSynchronizeEvent(iterEndEvent));
                ACLCHECK(aclrtEventElapsedTime(&iterMs, iterStartEvent, iterEndEvent));
                if (iter > 0) {
                    // 首帧含 Prepare（通道创建 ~1.2s），不计入稳态均值
                    eventElapsedTotalMs += iterMs;
                }
                std::cout << "rankId: " << myRank << ", perf iter " << (iter + 1) << "/" << totalRuns
                          << " event=" << (iterMs * 1000.0F) << "us" << std::endl;
                if (iter < totalRuns - 1) {
                    for (uint32_t j = 0; j < HEAVY_MEMSET_COUNT; j++) {
                        ACLCHECK(aclrtMemsetAsync(heavyBuf, HEAVY_BUF_SIZE, 0, HEAVY_BUF_SIZE, streamAicore));
                    }
                }
            }
        }
        if (ctx.mode == RunMode::PERF) {
            if (heavyBuf != nullptr) {
                (void)aclrtFree(heavyBuf);
            }
            const uint32_t steadyRuns = (totalRuns > 1) ? (totalRuns - 1) : 1;
            std::cout << "rankId: " << myRank
                      << ", event timing steady avg=" << (eventElapsedTotalMs * 1000.0F / steadyRuns) << "us/iter over "
                      << steadyRuns << " iters (end-to-end incl launch+sync gap, first frame excluded)" << std::endl;
            ACLCHECK(aclrtDestroyEvent(iterStartEvent));
            ACLCHECK(aclrtDestroyEvent(iterEndEvent));
        }
        // 兜底同步后统一释放 CCU 资源（实例销毁前双流必须已静默）
        (void)aclrtSynchronizeStream(streamAicore);
        (void)aclrtSynchronizeStream(streamCcu);
        const int releaseRet = static_cast<int>(ReleaseAllToAllMatmulContext(a2aCtx));
        if (runRet == 0) {
            runRet = releaseRet;
        }
        if (runRet != 0) {
            freeAll();
            return runRet;
        }

        int verifyRet = 0;
        if (ctx.mode == RunMode::PRECISION) {
            std::this_thread::sleep_for(std::chrono::seconds(ctx.rankId));
            verifyRet = VerifyOutputAgainstExpect(myRank, blockRows, N, output, outputSize, expectHost);
        }
        freeAll();
        return verifyRet;
    }();

    HCCLCHECK(HcclCommDestroy(hcclComm));
    ACLCHECK(aclrtDestroyStream(streamCcu));
    ACLCHECK(aclrtDestroyStream(streamAicore));
    ACLCHECK(aclrtResetDevice(ctx.rankId));
    return ctx.ret;
}

// 程序入口：参数解析 → aclInit + 查询 device 数（rankSize）→ rootInfo →
// 每 device 一线程 → join 聚合（任一失败 → 退出码非 0）
int main(int argc, char* argv[])
{
    ThreadContext cliParams; // 成员默认值 = 默认 case，CLI 覆盖
    if (!ParseCommandLine(argc, argv, cliParams)) {
        return 1;
    }

    std::cout << "Run mode: " << (cliParams.mode == RunMode::PERF ? "perf" : "precision") << ", M=" << cliParams.M
              << ", tileM=" << cliParams.tileM << ", K=" << cliParams.K << ", N=" << cliParams.N
              << ", data=" << cliParams.dataDir;
    if (cliParams.mode == RunMode::PERF) {
        std::cout << ", loop=" << cliParams.loopCount;
    }
    std::cout << std::endl;

    ACLCHECK(aclInit(NULL));
    uint32_t rankSize;
    ACLCHECK(aclrtGetDeviceCount(&rankSize));
    std::cout << "Found " << rankSize << " NPU device(s) available" << std::endl;

    if (rankSize == 0 || cliParams.M % rankSize != 0) {
        std::cout << "ERROR: M=" << cliParams.M << " must be divisible by rankSize=" << rankSize << std::endl;
        return 1;
    }
    const uint64_t blockRows = cliParams.M / rankSize;
    if (blockRows % cliParams.tileM != 0) {
        std::cout << "ERROR: blockRows=" << blockRows << " (=M/rankSize) must be divisible by tileM=" << cliParams.tileM
                  << std::endl;
        return 1;
    }
    if (blockRows / cliParams.tileM > MAX_COMMTURN) {
        std::cout << "ERROR: dataCommTurn=" << (blockRows / cliParams.tileM) << " exceeds MAX_COMMTURN=" << MAX_COMMTURN
                  << std::endl;
        return 1;
    }

    const char* schedMode = getenv("HCCL_OP_EXPANSION_MODE");
    if (schedMode == nullptr || std::string(schedMode) != "CCU_SCHED") {
        std::cout << "WARNING: HCCL_OP_EXPANSION_MODE=" << (schedMode ? schedMode : "(unset)")
                  << " (expected CCU_SCHED), CCU operations may fail!" << std::endl;
    } else {
        std::cout << "HCCL_OP_EXPANSION_MODE=" << schedMode << " OK" << std::endl;
    }

    int32_t rootRank = 0;
    ACLCHECK(aclrtSetDevice(rootRank));
    void* rootInfoBuf = nullptr;
    ACLCHECK(aclrtMallocHost(&rootInfoBuf, sizeof(HcclRootInfo)));
    HcclRootInfo* rootInfo = (HcclRootInfo*)rootInfoBuf;
    HCCLCHECK(HcclGetRootInfo(rootInfo));

    std::vector<std::thread> threads(rankSize);
    std::vector<ThreadContext> args(rankSize, cliParams);
    for (uint32_t i = 0; i < rankSize; i++) {
        args[i].rootInfo = rootInfo;
        args[i].rankId = i;
        args[i].rankSize = rankSize;
        threads[i] = std::thread(RunAllToAllMatmul, std::ref(args[i]));
    }
    for (uint32_t i = 0; i < rankSize; i++) {
        threads[i].join();
    }

    ACLCHECK(aclrtFreeHost(rootInfoBuf));
    ACLCHECK(aclFinalize());

    int finalRet = 0;
    for (uint32_t i = 0; i < rankSize; i++) {
        if (args[i].ret != 0) {
            std::cout << "rankId: " << i << " failed with ret=" << args[i].ret << std::endl;
            finalRet = (finalRet == 0) ? 1 : finalRet;
        }
    }
    if (finalRet == 0) {
        std::cout << "=== ALL RANKS PASS ===" << std::endl;
    } else {
        std::cout << "=== SOME RANKS FAILED ===" << std::endl;
    }
    return finalRet;
}
