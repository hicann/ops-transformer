/*! \file test_aclnn_block_sparse_attention_grad_hif8.cpp
 *  \brief End-to-end AscendCL validation for the HiF8 BNSD BSAG path.
 *
 *  The input directory is generated by tests/reference_bsag_hif8.py
 *  --save-raw-dir.  Run the static and dynamic subdirectories separately.
 */

#include <algorithm>
#include <cmath>
#include <cstdint>
#include <cstdio>
#include <filesystem>
#include <fstream>
#include <numeric>
#include <string>
#include <vector>

#include "acl/acl.h"
#include "aclnnop/aclnn_block_sparse_attention_grad_v2.h"

namespace {

struct TensorHandle {
    void* device{nullptr};
    aclTensor* tensor{nullptr};
};

template <typename T>
bool ReadBinary(const std::filesystem::path& path, size_t count, std::vector<T>& data)
{
    data.resize(count);
    std::ifstream stream(path, std::ios::binary);
    if (!stream ||
        !stream.read(reinterpret_cast<char*>(data.data()), static_cast<std::streamsize>(count * sizeof(T)))) {
        std::fprintf(stderr, "failed to read %s (%zu elements)\n", path.string().c_str(), count);
        return false;
    }
    return stream.peek() == std::ifstream::traits_type::eof();
}

size_t ShapeSize(const std::vector<int64_t>& shape)
{
    return std::accumulate(shape.begin(), shape.end(), static_cast<size_t>(1),
                           [](size_t x, int64_t y) { return x * static_cast<size_t>(y); });
}

template <typename T>
aclError CreateTensor(const std::vector<T>& host, const std::vector<int64_t>& shape, aclDataType type,
                      TensorHandle& handle)
{
    const size_t bytes = host.size() * sizeof(T);
    aclError ret = aclrtMalloc(&handle.device, bytes, ACL_MEM_MALLOC_HUGE_FIRST);
    if (ret != ACL_SUCCESS) {
        return ret;
    }
    ret = aclrtMemcpy(handle.device, bytes, host.data(), bytes, ACL_MEMCPY_HOST_TO_DEVICE);
    if (ret != ACL_SUCCESS) {
        return ret;
    }
    std::vector<int64_t> strides(shape.size(), 1);
    for (int64_t i = static_cast<int64_t>(shape.size()) - 2; i >= 0; --i) {
        strides[i] = strides[i + 1] * shape[i + 1];
    }
    handle.tensor = aclCreateTensor(shape.data(), shape.size(), type, strides.data(), 0, ACL_FORMAT_ND, shape.data(),
                                    shape.size(), handle.device);
    return handle.tensor == nullptr ? ACL_ERROR_INVALID_PARAM : ACL_SUCCESS;
}

void DestroyTensor(TensorHandle& handle)
{
    if (handle.tensor != nullptr) {
        aclDestroyTensor(handle.tensor);
    }
    if (handle.device != nullptr) {
        aclrtFree(handle.device);
    }
    handle = {};
}

float Bf16ToFloat(uint16_t value)
{
    union {
        uint32_t bits;
        float value;
    } converted{static_cast<uint32_t>(value) << 16};
    return converted.value;
}

struct Metrics {
    double maxAbs{0.0};
    double meanAbs{0.0};
    double relativeL2{0.0};
    double cosine{0.0};
};

Metrics Compare(const std::vector<uint16_t>& actual, const std::vector<uint16_t>& expected)
{
    double sumAbs = 0.0;
    double sumDiff2 = 0.0;
    double sumExpected2 = 0.0;
    double sumActual2 = 0.0;
    double dot = 0.0;
    Metrics result;
    for (size_t i = 0; i < actual.size(); ++i) {
        const double lhs = Bf16ToFloat(actual[i]);
        const double rhs = Bf16ToFloat(expected[i]);
        const double diff = lhs - rhs;
        result.maxAbs = std::max(result.maxAbs, std::abs(diff));
        sumAbs += std::abs(diff);
        sumDiff2 += diff * diff;
        sumExpected2 += rhs * rhs;
        sumActual2 += lhs * lhs;
        dot += lhs * rhs;
    }
    result.meanAbs = sumAbs / static_cast<double>(actual.size());
    result.relativeL2 = std::sqrt(sumDiff2) / std::max(std::sqrt(sumExpected2), 1.0e-30);
    const double normProduct = std::sqrt(sumActual2 * sumExpected2);
    result.cosine = normProduct == 0.0 ? 1.0 : dot / normProduct;
    return result;
}

void PrintMetrics(const char* name, const Metrics& value)
{
    std::printf("%s: cosine=%.9f relative_l2=%.9f max_abs=%.9g mean_abs=%.9g\n", name, value.cosine, value.relativeL2,
                value.maxAbs, value.meanAbs);
}

} // namespace

int main(int argc, char** argv)
{
    if (argc != 2) {
        std::fprintf(stderr, "usage: %s <static-or-dynamic-raw-case-directory>\n", argv[0]);
        return 2;
    }
    const std::filesystem::path root(argv[1]);
    constexpr int64_t batch = 1;
    constexpr int64_t qHeads = 4;
    constexpr int64_t kvHeads = 2;
    constexpr int64_t qSeq = 128;
    constexpr int64_t kvSeq = 128;
    constexpr int64_t dim = 128;
    constexpr int64_t blockM = 32;
    constexpr int64_t blockN = 32;
    const std::vector<int64_t> qShape{batch, qHeads, qSeq, dim};
    const std::vector<int64_t> kvShape{batch, kvHeads, kvSeq, dim};
    const std::vector<int64_t> lseShape{batch, qHeads, qSeq};
    const std::vector<int64_t> maskShape{batch, qHeads, qSeq / blockM, kvSeq / blockN};
    const std::vector<int64_t> scalarShape{1};

    std::vector<uint8_t> q, k, v, dout, mask;
    std::vector<uint16_t> out, expectedDq, expectedDk, expectedDv;
    std::vector<float> lse, qDescale, kDescale, vDescale, doDescale, pScale, dsScale;
    const bool loaded =
        ReadBinary(root / "q_hif8.bin", ShapeSize(qShape), q) &&
        ReadBinary(root / "k_hif8.bin", ShapeSize(kvShape), k) &&
        ReadBinary(root / "v_hif8.bin", ShapeSize(kvShape), v) &&
        ReadBinary(root / "dout_hif8.bin", ShapeSize(qShape), dout) &&
        ReadBinary(root / "attention_out_bf16.bin", ShapeSize(qShape), out) &&
        ReadBinary(root / "softmax_lse_fp32.bin", ShapeSize(lseShape), lse) &&
        ReadBinary(root / "block_sparse_mask_u8.bin", ShapeSize(maskShape), mask) &&
        ReadBinary(root / "q_descale_fp32.bin", 1, qDescale) && ReadBinary(root / "k_descale_fp32.bin", 1, kDescale) &&
        ReadBinary(root / "v_descale_fp32.bin", 1, vDescale) &&
        ReadBinary(root / "dout_descale_fp32.bin", 1, doDescale) && ReadBinary(root / "p_scale_fp32.bin", 1, pScale) &&
        ReadBinary(root / "ds_scale_fp32.bin", 1, dsScale) &&
        ReadBinary(root / "expected_dq_bf16.bin", ShapeSize(qShape), expectedDq) &&
        ReadBinary(root / "expected_dk_bf16.bin", ShapeSize(kvShape), expectedDk) &&
        ReadBinary(root / "expected_dv_bf16.bin", ShapeSize(kvShape), expectedDv);
    if (!loaded) {
        return 2;
    }

    aclrtStream stream = nullptr;
    aclError ret = aclInit(nullptr);
    if (ret != ACL_SUCCESS || (ret = aclrtSetDevice(0)) != ACL_SUCCESS ||
        (ret = aclrtCreateStream(&stream)) != ACL_SUCCESS) {
        std::fprintf(stderr, "AscendCL initialization failed: %d\n", ret);
        return 3;
    }

    std::vector<uint16_t> zerosQ(ShapeSize(qShape), 0);
    std::vector<uint16_t> zerosKv(ShapeSize(kvShape), 0);
    TensorHandle qTensor, kTensor, vTensor, doutTensor, outTensor, lseTensor, maskTensor;
    TensorHandle qDescaleTensor, kDescaleTensor, vDescaleTensor, doDescaleTensor, pScaleTensor, dsScaleTensor;
    TensorHandle dqTensor, dkTensor, dvTensor;
    std::vector<TensorHandle*> handles{&qTensor,        &kTensor,        &vTensor,         &doutTensor,
                                       &outTensor,      &lseTensor,      &maskTensor,      &qDescaleTensor,
                                       &kDescaleTensor, &vDescaleTensor, &doDescaleTensor, &pScaleTensor,
                                       &dsScaleTensor,  &dqTensor,       &dkTensor,        &dvTensor};
    auto createAll = [&]() -> aclError {
        aclError status = CreateTensor(q, qShape, ACL_HIFLOAT8, qTensor);
        if (status == ACL_SUCCESS)
            status = CreateTensor(k, kvShape, ACL_HIFLOAT8, kTensor);
        if (status == ACL_SUCCESS)
            status = CreateTensor(v, kvShape, ACL_HIFLOAT8, vTensor);
        if (status == ACL_SUCCESS)
            status = CreateTensor(dout, qShape, ACL_HIFLOAT8, doutTensor);
        if (status == ACL_SUCCESS)
            status = CreateTensor(out, qShape, ACL_BF16, outTensor);
        if (status == ACL_SUCCESS)
            status = CreateTensor(lse, lseShape, ACL_FLOAT, lseTensor);
        if (status == ACL_SUCCESS)
            status = CreateTensor(mask, maskShape, ACL_UINT8, maskTensor);
        if (status == ACL_SUCCESS)
            status = CreateTensor(qDescale, scalarShape, ACL_FLOAT, qDescaleTensor);
        if (status == ACL_SUCCESS)
            status = CreateTensor(kDescale, scalarShape, ACL_FLOAT, kDescaleTensor);
        if (status == ACL_SUCCESS)
            status = CreateTensor(vDescale, scalarShape, ACL_FLOAT, vDescaleTensor);
        if (status == ACL_SUCCESS)
            status = CreateTensor(doDescale, scalarShape, ACL_FLOAT, doDescaleTensor);
        if (status == ACL_SUCCESS)
            status = CreateTensor(pScale, scalarShape, ACL_FLOAT, pScaleTensor);
        if (status == ACL_SUCCESS)
            status = CreateTensor(dsScale, scalarShape, ACL_FLOAT, dsScaleTensor);
        if (status == ACL_SUCCESS)
            status = CreateTensor(zerosQ, qShape, ACL_BF16, dqTensor);
        if (status == ACL_SUCCESS)
            status = CreateTensor(zerosKv, kvShape, ACL_BF16, dkTensor);
        if (status == ACL_SUCCESS)
            status = CreateTensor(zerosKv, kvShape, ACL_BF16, dvTensor);
        return status;
    };
    ret = createAll();
    if (ret != ACL_SUCCESS) {
        std::fprintf(stderr, "tensor creation failed: %d\n", ret);
        for (auto* handle : handles)
            DestroyTensor(*handle);
        return 4;
    }

    int64_t blockData[2]{blockM, blockN};
    int64_t qSeqData[1]{qSeq};
    int64_t kvSeqData[1]{kvSeq};
    aclIntArray* blockShape = aclCreateIntArray(blockData, 2);
    aclIntArray* actualQ = aclCreateIntArray(qSeqData, 1);
    aclIntArray* actualKv = aclCreateIntArray(kvSeqData, 1);
    char qLayout[] = "BNSD";
    char kvLayout[] = "BNSD";
    uint64_t workspaceSize = 0;
    aclOpExecutor* executor = nullptr;
    ret = aclnnBlockSparseAttentionGradV2GetWorkspaceSize(
        doutTensor.tensor, qTensor.tensor, kTensor.tensor, vTensor.tensor, outTensor.tensor, lseTensor.tensor,
        maskTensor.tensor, nullptr, blockShape, actualQ, actualKv, qDescaleTensor.tensor, kDescaleTensor.tensor,
        vDescaleTensor.tensor, doDescaleTensor.tensor, pScaleTensor.tensor, dsScaleTensor.tensor, qLayout, kvLayout,
        kvHeads, 0, 1.0 / std::sqrt(static_cast<double>(dim)), 2147483647, 2147483647, 5, dqTensor.tensor,
        dkTensor.tensor, dvTensor.tensor, &workspaceSize, &executor);

    void* workspace = nullptr;
    if (ret == ACL_SUCCESS && workspaceSize > 0) {
        ret = aclrtMalloc(&workspace, workspaceSize, ACL_MEM_MALLOC_HUGE_FIRST);
    }
    if (ret == ACL_SUCCESS) {
        ret = aclnnBlockSparseAttentionGradV2(workspace, workspaceSize, executor, stream);
    }
    if (ret == ACL_SUCCESS) {
        ret = aclrtSynchronizeStream(stream);
    }

    std::vector<uint16_t> actualDq(ShapeSize(qShape)), actualDk(ShapeSize(kvShape)), actualDv(ShapeSize(kvShape));
    if (ret == ACL_SUCCESS) {
        ret = aclrtMemcpy(actualDq.data(), actualDq.size() * sizeof(uint16_t), dqTensor.device,
                          actualDq.size() * sizeof(uint16_t), ACL_MEMCPY_DEVICE_TO_HOST);
    }
    if (ret == ACL_SUCCESS) {
        ret = aclrtMemcpy(actualDk.data(), actualDk.size() * sizeof(uint16_t), dkTensor.device,
                          actualDk.size() * sizeof(uint16_t), ACL_MEMCPY_DEVICE_TO_HOST);
    }
    if (ret == ACL_SUCCESS) {
        ret = aclrtMemcpy(actualDv.data(), actualDv.size() * sizeof(uint16_t), dvTensor.device,
                          actualDv.size() * sizeof(uint16_t), ACL_MEMCPY_DEVICE_TO_HOST);
    }

    int exitCode = 5;
    if (ret == ACL_SUCCESS) {
        const Metrics dqMetrics = Compare(actualDq, expectedDq);
        const Metrics dkMetrics = Compare(actualDk, expectedDk);
        const Metrics dvMetrics = Compare(actualDv, expectedDv);
        std::printf("workspace_bytes=%lu ds_scale=%g (%s)\n", workspaceSize, dsScale[0],
                    dsScale[0] == 0.0f ? "dynamic" : "static");
        PrintMetrics("dq", dqMetrics);
        PrintMetrics("dk", dkMetrics);
        PrintMetrics("dv", dvMetrics);
        const bool passed = dqMetrics.cosine >= 0.98 && dkMetrics.cosine >= 0.98 && dvMetrics.cosine >= 0.98 &&
                            dqMetrics.relativeL2 <= 0.25 && dkMetrics.relativeL2 <= 0.25 &&
                            dvMetrics.relativeL2 <= 0.25;
        std::printf("RESULT=%s\n", passed ? "PASS" : "FAIL");
        exitCode = passed ? 0 : 6;
    } else {
        std::fprintf(stderr, "HiF8 BSAG execution failed: %d\n", ret);
    }

    if (workspace != nullptr)
        aclrtFree(workspace);
    aclDestroyIntArray(blockShape);
    aclDestroyIntArray(actualQ);
    aclDestroyIntArray(actualKv);
    for (auto* handle : handles)
        DestroyTensor(*handle);
    aclrtDestroyStream(stream);
    aclrtResetDevice(0);
    aclFinalize();
    return exitCode;
}
